// Command codeeval-fixtures builds the fixture scenario repositories and runs
// the real codeeval binary on every base→variant pair, writing paired JSON
// and Markdown reports plus an index. It is a development tool for producing
// examples/fixtures; tests build the same repositories via fixturerepo.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/cameron/code-evaluator/internal/fixturerepo"
	"github.com/cameron/code-evaluator/internal/report"
)

func main() {
	bin := flag.String("codeeval", "", "path to the codeeval binary")
	fixtures := flag.String("fixtures", "testdata/fixtures", "fixture scenarios root")
	repos := flag.String("repos", "", "directory for generated fixture repositories (outside this repo)")
	out := flag.String("out", "examples/fixtures", "report output directory")
	flag.Parse()
	if *bin == "" || *repos == "" {
		fmt.Fprintln(os.Stderr, "usage: codeeval-fixtures --codeeval BIN --repos DIR [--out DIR]")
		os.Exit(2)
	}
	if err := run(*bin, *fixtures, *repos, *out); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run(bin, fixtures, repos, out string) error {
	list, err := fixturerepo.Load(fixtures)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	var index strings.Builder
	index.WriteString("# Fixture reports\n\nGenerated by `codeeval-fixtures` running the real `codeeval` CLI on each base→variant pair.\n")
	index.WriteString("Variants of a scenario implement the same behaviour (same tests) but differ in quality; see each scenario README in testdata/fixtures.\n\n")
	index.WriteString("| Scenario | Variant | duplication | complexity | dependencies | scope | obsolete | correctness | Report |\n|---|---|---:|---:|---:|---:|---:|---:|---|\n")
	for _, s := range list {
		dst := filepath.Join(repos, s.Name)
		if err := os.RemoveAll(dst); err != nil {
			return err
		}
		refs, err := s.BuildRepo(dst)
		if err != nil {
			return err
		}
		variants := s.Variants
		if s.Name == "edge" {
			variants = append([]string{"base"}, variants...) // unchanged baseline
		}
		for _, v := range variants {
			name := s.Name + "--" + v
			args := []string{"evaluate", "--repo", dst, "--base", refs["base"], "--target", refs[v], "--no-cache",
				"--output", filepath.Join(out, name+".json"), "--summary", filepath.Join(out, name+".md"), "--format", "none"}
			if s.Config != "" {
				args = append(args, "--config", s.Config)
			}
			cmd := exec.Command(bin, args...)
			cmd.Stderr = os.Stderr
			if err := cmd.Run(); err != nil {
				return fmt.Errorf("%s: %w", name, err)
			}
			data, err := os.ReadFile(filepath.Join(out, name+".json"))
			if err != nil {
				return err
			}
			var r report.Report
			if err := json.Unmarshal(data, &r); err != nil {
				return err
			}
			cells := map[string]string{}
			for _, res := range r.Results {
				c := "n/a (" + res.Status + ")"
				if res.Score != nil {
					c = fmt.Sprintf("%+d", *res.Score)
					if *res.Score == 0 {
						c = "0"
					}
					if res.Status != "ok" {
						c += " (" + res.Status + ")"
					}
				}
				cells[res.Analyzer] = c
			}
			label := v
			if v == "base" {
				label = "base (unchanged)"
			}
			fmt.Fprintf(&index, "| %s | %s | %s | %s | %s | %s | %s | %s | [md](%s.md) · [json](%s.json) |\n", s.Name, label,
				cells["duplication"], cells["complexity"], cells["dependencies"], cells["scope"], cells["obsolete"], cells["correctness"], name, name)
		}
	}
	return os.WriteFile(filepath.Join(out, "README.md"), []byte(index.String()), 0o644)
}
