// Package csharp is the C# language adapter, built on Tree-sitter
// (tree-sitter-c-sharp).
//
// It extracts classes, structs, records, interfaces and enums (nested types
// named Outer.Inner); methods, constructors, destructors, operators and
// properties/indexers with bodies as callables; per-callable cyclomatic
// complexity, decisions, nesting, length and statements; exact/structural
// fingerprints; name-based references; and a directory-level dependency
// graph from `using` directives resolved to the directories that declare
// each namespace.
//
// It does not type-check, resolve overloads, follow implicit access to
// enclosing namespaces or fully qualified names, or read .csproj
// ProjectReference/PackageReference.
package csharp

import (
	"bytes"
	"path"
	"regexp"
	"sort"
	"strings"

	sitter "github.com/tree-sitter/go-tree-sitter"
	tscs "github.com/tree-sitter/tree-sitter-c-sharp/bindings/go"

	"github.com/cameron/code-evaluator/internal/lang"
	"github.com/cameron/code-evaluator/internal/lang/fingerprint"
	"github.com/cameron/code-evaluator/internal/lang/sitterutil"
	"github.com/cameron/code-evaluator/internal/model"
)

// Adapter implements lang.Adapter for C#.
type Adapter struct{ language *sitter.Language }

// New returns the C# adapter.
func New() *Adapter { return &Adapter{language: sitter.NewLanguage(tscs.Language())} }

func (a *Adapter) ID() string           { return "csharp" }
func (a *Adapter) Version() string      { return "cs-adapter/1+tree-sitter-c-sharp/0.23.5" }
func (a *Adapter) Extensions() []string { return []string{".cs"} }

func (a *Adapter) Capabilities() map[lang.Capability]string {
	return map[lang.Capability]string{
		lang.CapSymbols:      "classes, structs, records, interfaces, enums (nested as Outer.Inner); methods, constructors, destructors, operators and properties/indexers with bodies",
		lang.CapComplexity:   "cyclomatic = 1 + if/for/foreach/while/do/switch section/switch-expression arm (not `_`)/catch/ternary/&&/||/??; nesting counts if/loops/switch/catch/lambdas/local functions (inner lambdas and local functions count toward the enclosing callable); else-if not nested",
		lang.CapFingerprints: "exact token text and structural kinds (identifiers/literals abstracted), comments ignored",
		lang.CapDependencies: "directory-level graph from using directives resolved to the directories that declare each namespace; namespaces not declared in the repository are external; test files excluded",
		lang.CapReferences:   "name-based identifier references; member access recorded as object.Name; no type resolution",
	}
}

func (a *Adapter) Limits() []string {
	return []string{
		"no type checking or overload resolution: references are matched by name",
		"graph edges come from using directives only: implicit access to enclosing namespaces, fully qualified names and global usings in other files are not followed",
		".csproj ProjectReference and PackageReference are not read; a namespace declared in several directories links to all of them",
		"graph units are directories; directory cycles are legal in C# and indicate coupling, not build errors",
		"lambdas and local functions are measured as part of their enclosing callable",
		"top-level statements (Program.cs without a Main method) are not measured as a callable",
	}
}

var testPathRe = regexp.MustCompile(`(?i)(^|/)[^/]*\.(tests?|unittests?|integrationtests?|specs?)(/|$)|(^|/)tests?/|tests?\.cs$`)

func (a *Adapter) IsTestPath(p string) bool { return testPathRe.MatchString(p) }

func (a *Adapter) PackageOf(p string) string { return path.Dir(p) }

var generatedRe = regexp.MustCompile(`(?i)<auto-generated|// *generated by|@generated`)

// ParseSyntax returns the Tree-sitter syntax tree (lang.SyntaxParser).
func (a *Adapter) ParseSyntax(src []byte) (*sitter.Tree, error) {
	return sitterutil.Parse(a.language, src)
}

// Parse parses C# source.
func (a *Adapter) Parse(src []byte) (*model.ParsedFile, error) {
	tree, err := sitterutil.Parse(a.language, src)
	if err != nil {
		return nil, err
	}
	defer tree.Close()
	root := tree.RootNode()
	pf := &model.ParsedFile{Refs: map[string]int{}, Lines: bytes.Count(src, []byte{'\n'}) + 1}
	head := src
	if len(head) > 600 {
		head = head[:600]
	}
	pf.Generated = generatedRe.Match(head)
	p := &fileParser{src: src, pf: pf, errs: sitterutil.Errors{Language: "csharp"}}
	if root.HasError() {
		p.errs.Collect(root)
		pf.ParseErrors = p.errs.Diags
	}
	p.members(root, "")
	p.refs(root)
	sort.SliceStable(pf.Symbols, func(i, j int) bool { return pf.Symbols[i].StartLine < pf.Symbols[j].StartLine })
	return pf, nil
}

type fileParser struct {
	src  []byte
	pf   *model.ParsedFile
	errs sitterutil.Errors
}

var line, endLine = sitterutil.Line, sitterutil.EndLine

func (p *fileParser) text(n *sitter.Node) string {
	if n == nil {
		return ""
	}
	return n.Utf8Text(p.src)
}

var typeKinds = map[string]string{
	"class_declaration": "class", "struct_declaration": "struct", "record_declaration": "record",
	"record_struct_declaration": "record", "interface_declaration": "interface", "enum_declaration": "enum",
}

// members walks a compilation unit, namespace or type body.
func (p *fileParser) members(n *sitter.Node, container string) {
	for i := uint(0); i < n.NamedChildCount(); i++ {
		c := n.NamedChild(i)
		switch k := c.Kind(); k {
		case "using_directive":
			p.using(c)
		case "namespace_declaration":
			if p.pf.PackageName == "" {
				p.pf.PackageName = p.text(c.ChildByFieldName("name"))
			}
			if b := c.ChildByFieldName("body"); b != nil {
				p.members(b, container)
			}
		case "file_scoped_namespace_declaration":
			if p.pf.PackageName == "" {
				p.pf.PackageName = p.text(c.ChildByFieldName("name"))
			}
			p.members(c, container)
		case "declaration_list":
			p.members(c, container)
		default:
			if kind, ok := typeKinds[k]; ok {
				p.typeDecl(c, container, kind)
			}
		}
	}
}

func (p *fileParser) using(n *sitter.Node) {
	imp := model.Import{Line: line(n)}
	if a := n.ChildByFieldName("name"); a != nil {
		imp.Name = p.text(a) // using Alias = X.Y;
	}
	for i := uint(0); i < n.ChildCount(); i++ {
		c := n.Child(i)
		switch c.Kind() {
		case "static":
			imp.Name = "static"
		case "qualified_name", "identifier", "generic_name", "alias_qualified_name":
			if n.FieldNameForChild(uint32(i)) != "name" {
				imp.Path = p.text(c)
			}
		}
	}
	if imp.Path != "" {
		p.pf.Imports = append(p.pf.Imports, imp)
	}
}

func hasModifier(f *fileParser, n *sitter.Node, mods ...string) bool {
	for i := uint(0); i < n.NamedChildCount(); i++ {
		c := n.NamedChild(i)
		if c.Kind() != "modifier" {
			continue
		}
		t := f.text(c)
		for _, m := range mods {
			if t == m {
				return true
			}
		}
	}
	return false
}

func (p *fileParser) typeDecl(n *sitter.Node, container, kind string) {
	name := p.text(n.ChildByFieldName("name"))
	if container != "" {
		name = container + "." + name
	}
	exported := hasModifier(p, n, "public", "protected")
	var fb fingerprint.Builder
	if body := n.ChildByFieldName("body"); body != nil {
		for i := uint(0); i < body.NamedChildCount(); i++ {
			if nn := body.NamedChild(i).ChildByFieldName("name"); nn != nil {
				fb.Add(p.text(nn), "ID")
			}
		}
	}
	p.pf.Symbols = append(p.pf.Symbols, model.Symbol{Name: name, Kind: model.KindType, Exported: exported, StartLine: line(n), EndLine: endLine(n),
		ExactFP: fb.Exact(), StructFP: fb.Struct(), Tokens: fb.Tokens(), Signature: kind, InErrorRegion: p.errs.In(line(n), endLine(n))})
	body := n.ChildByFieldName("body")
	if body == nil {
		return
	}
	iface := kind == "interface"
	for i := uint(0); i < body.NamedChildCount(); i++ {
		m := body.NamedChild(i)
		mexp := iface || hasModifier(p, m, "public", "protected")
		switch k := m.Kind(); k {
		case "method_declaration", "constructor_declaration", "destructor_declaration", "operator_declaration", "conversion_operator_declaration":
			if b := m.ChildByFieldName("body"); b != nil {
				mname := p.text(m.ChildByFieldName("name"))
				switch k {
				case "destructor_declaration":
					mname = "~" + mname
				case "operator_declaration":
					mname = "operator" + p.text(m.ChildByFieldName("operator"))
				case "conversion_operator_declaration":
					mname = "operator " + p.text(m.ChildByFieldName("type"))
				}
				p.callable(m, m, mname, name, exported && mexp, b)
			}
		case "property_declaration", "indexer_declaration":
			if p.hasBody(m) {
				mname := "this[]"
				if nn := m.ChildByFieldName("name"); nn != nil {
					mname = p.text(nn)
				}
				p.callable(m, m, mname, name, exported && mexp, m)
			}
		default:
			if tk, ok := typeKinds[k]; ok {
				p.typeDecl(m, name, tk)
			}
		}
	}
}

// hasBody reports whether a property or indexer has accessor bodies or an
// expression body (auto-properties have neither and are not callables).
func (p *fileParser) hasBody(m *sitter.Node) bool {
	if m.ChildByFieldName("value") != nil {
		if v := m.ChildByFieldName("value"); v.Kind() == "arrow_expression_clause" {
			return true
		}
	}
	found := false
	sitterutil.Walk(m, func(n *sitter.Node) bool {
		if found {
			return false
		}
		if n.Kind() == "arrow_expression_clause" || (n.Kind() == "block" && n.Parent() != nil && n.Parent().Kind() == "accessor_declaration") {
			found = true
		}
		return true
	})
	return found
}

// callable records a callable symbol; span covers its lines, body is
// measured.
func (p *fileParser) callable(fn, span *sitter.Node, name, container string, exported bool, body *sitter.Node) {
	sym := model.Symbol{Name: name, Container: container, Kind: model.KindMethod, Exported: exported, StartLine: line(span), EndLine: endLine(span)}
	if container == "" {
		sym.Kind = model.KindFunction
	}
	if params := fn.ChildByFieldName("parameters"); params != nil {
		sym.Signature = strings.Join(strings.Fields(p.text(params)), " ")
	}
	var fb fingerprint.Builder
	if params := fn.ChildByFieldName("parameters"); params != nil {
		p.tokens(params, &fb)
	}
	p.tokens(body, &fb)
	sym.ExactFP, sym.StructFP, sym.Tokens, sym.MinHash = fb.Exact(), fb.Struct(), fb.Tokens(), fb.MinHash()
	m := &model.Metrics{Lines: sym.EndLine - sym.StartLine + 1}
	sitterutil.Measure(body, 0, m, measureSpec)
	m.Cyclomatic = 1 + m.Decisions
	sym.Metrics = m
	sym.InErrorRegion = p.errs.In(sym.StartLine, sym.EndLine)
	p.pf.Symbols = append(p.pf.Symbols, sym)
}

var literalKinds = map[string]bool{
	"string_literal": true, "verbatim_string_literal": true, "raw_string_literal": true, "interpolated_string_expression": true,
	"integer_literal": true, "real_literal": true, "character_literal": true, "boolean_literal": true, "null_literal": true,
}

func (p *fileParser) tokens(n *sitter.Node, fb *fingerprint.Builder) {
	kind := n.Kind()
	if kind == "comment" {
		return
	}
	if literalKinds[kind] {
		fb.Add(p.text(n), "LIT")
		return
	}
	if n.ChildCount() == 0 {
		if kind == "identifier" {
			fb.Add(p.text(n), "ID")
		} else {
			fb.Add(p.text(n), kind)
		}
		return
	}
	for i := uint(0); i < n.ChildCount(); i++ {
		p.tokens(n.Child(i), fb)
	}
}

var nestingKinds = map[string]bool{
	"if_statement": true, "for_statement": true, "foreach_statement": true, "while_statement": true, "do_statement": true,
	"switch_statement": true, "switch_expression": true, "catch_clause": true, "lambda_expression": true,
	"anonymous_method_expression": true, "local_function_statement": true,
}

var measureSpec = &sitterutil.MeasureSpec{
	Decision: func(n *sitter.Node) bool {
		switch n.Kind() {
		case "if_statement", "for_statement", "foreach_statement", "while_statement", "do_statement", "catch_clause", "conditional_expression":
			return true
		case "switch_section":
			// a section with only a default label is not a decision
			for i := uint(0); i < n.ChildCount(); i++ {
				if k := n.Child(i).Kind(); k == "case" || strings.HasSuffix(k, "pattern") || k == "case_switch_label" || k == "case_pattern_switch_label" {
					return true
				}
			}
			return false
		case "switch_expression_arm":
			first := n.NamedChild(0)
			return first == nil || first.Kind() != "discard"
		}
		return sitterutil.LogicalOp(n, "&&", "||", "??")
	},
	Statement: func(kind string) bool {
		return strings.HasSuffix(kind, "_statement") && kind != "block"
	},
	Nests: func(n *sitter.Node) bool {
		return nestingKinds[n.Kind()] && !(n.Kind() == "if_statement" && n.Parent() != nil && n.Parent().Kind() == "if_statement")
	},
}

// refs records name-based identifier uses, skipping declaration names.
func (p *fileParser) refs(root *sitter.Node) {
	var visit func(n *sitter.Node)
	visit = func(n *sitter.Node) {
		switch n.Kind() {
		case "comment", "string_literal", "verbatim_string_literal", "raw_string_literal", "using_directive":
			return
		case "member_access_expression":
			obj, name := n.ChildByFieldName("expression"), n.ChildByFieldName("name")
			if obj != nil && name != nil && obj.Kind() == "identifier" {
				p.pf.Refs[p.text(obj)+"."+p.text(name)]++
			}
			if name != nil {
				p.pf.Refs[p.text(name)]++
			}
			if obj != nil {
				visit(obj)
			}
			return
		case "identifier":
			if par := n.Parent(); par != nil {
				if nn := par.ChildByFieldName("name"); nn != nil && nn.StartByte() == n.StartByte() && declKinds[par.Kind()] {
					return
				}
			}
			p.pf.Refs[p.text(n)]++
			return
		}
		for i := uint(0); i < n.ChildCount(); i++ {
			visit(n.Child(i))
		}
	}
	visit(root)
}

var declKinds = map[string]bool{
	"class_declaration": true, "struct_declaration": true, "record_declaration": true, "interface_declaration": true, "enum_declaration": true,
	"method_declaration": true, "constructor_declaration": true, "destructor_declaration": true, "property_declaration": true,
	"local_function_statement": true, "namespace_declaration": true, "file_scoped_namespace_declaration": true,
}

// BuildGraph builds the directory graph: each using directive links the
// file's directory to the directories that declare that namespace.
func (a *Adapter) BuildGraph(in lang.GraphInput) (*lang.Graph, []model.Diagnostic) {
	g := lang.NewGraph()
	g.Note = "C# directories linked by using directives to the directories declaring each namespace (non-test files); namespaces not declared in the repository are external"
	inGraph := func(f lang.GraphFile) bool { return f.Class == model.ClassSource || f.Class == model.ClassGenerated }
	declared := map[string]map[string]bool{} // namespace -> directories
	for _, f := range in.Files {
		if !inGraph(f) {
			continue
		}
		dir := path.Dir(f.Path)
		g.Nodes[dir] = true
		if f.Parsed == nil || f.Parsed.PackageName == "" {
			continue
		}
		ns := f.Parsed.PackageName
		if declared[ns] == nil {
			declared[ns] = map[string]bool{}
		}
		declared[ns][dir] = true
	}
	for _, f := range in.Files {
		if !inGraph(f) || f.Parsed == nil {
			continue
		}
		from := path.Dir(f.Path)
		for _, imp := range f.Parsed.Imports {
			dirs := declared[imp.Path]
			if len(dirs) == 0 {
				ext := g.External[from]
				if ext == nil {
					ext = map[string]bool{}
					g.External[from] = ext
				}
				ext[imp.Path] = true
				continue
			}
			for to := range dirs {
				g.AddEdge(from, to, model.Location{File: f.Path, Line: imp.Line})
			}
		}
	}
	return g, nil
}
