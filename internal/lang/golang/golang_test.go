package golang

import "testing"

const sample = `// Code generated by x. DO NOT EDIT.

package demo

import (
	"fmt"
	str "strings"
)

type Server struct{ name string }

func (s *Server) Handle(a, b int) int {
	if a > 0 && b > 0 { // 2 decisions
		for i := 0; i < a; i++ { // 1
			if i%2 == 0 { // 1
				fmt.Println(i)
			}
		}
	} else if a < 0 { // 1, same nesting level
		return -1
	}
	switch b {
	case 1: // 1
		return 1
	default:
	}
	return str.ToUpper(s.name) + helper()
}

func helper() string { return "x" }
`

func TestParseGo(t *testing.T) {
	pf, err := New().Parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	if !pf.Generated || pf.PackageName != "demo" || len(pf.Imports) != 2 || pf.Imports[1].Name != "str" {
		t.Fatalf("header: %+v", pf)
	}
	if len(pf.Symbols) != 3 {
		t.Fatalf("symbols: %+v", pf.Symbols)
	}
	h := pf.Symbols[1]
	if h.Name != "Handle" || h.Container != "Server" || !h.Exported || h.Kind != "method" {
		t.Fatalf("method: %+v", h)
	}
	if h.Metrics.Cyclomatic != 7 || h.Metrics.MaxNesting != 3 {
		t.Fatalf("metrics: %+v", h.Metrics)
	}
	if pf.Refs["helper"] != 1 || pf.Refs["str.ToUpper"] != 1 {
		t.Fatalf("refs: %v", pf.Refs)
	}
	if len(pf.ParseErrors) != 0 {
		t.Fatalf("unexpected errors %v", pf.ParseErrors)
	}
	bad, _ := New().Parse([]byte("package x\nfunc f( {\n"))
	if len(bad.ParseErrors) == 0 {
		t.Fatal("expected parse error")
	}
}

func TestRenameKeepsFingerprint(t *testing.T) {
	a, _ := New().Parse([]byte("package x\n// doc\nfunc A(v int) int { return v * 2 }\n"))
	b, _ := New().Parse([]byte("package x\nfunc B(v int) int {\n\treturn v * 2 // twice\n}\n"))
	c, _ := New().Parse([]byte("package x\nfunc C(w int) int { return w * 3 }\n"))
	if a.Symbols[0].ExactFP != b.Symbols[0].ExactFP {
		t.Fatal("rename/format should keep exact fingerprint")
	}
	if a.Symbols[0].ExactFP == c.Symbols[0].ExactFP || a.Symbols[0].StructFP != c.Symbols[0].StructFP {
		t.Fatal("renamed identifiers/literals should keep only structural fingerprint")
	}
}
